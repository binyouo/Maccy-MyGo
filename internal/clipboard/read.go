package clipboard

import (
	"strings"

	"github.com/binyouo/Maccy-MyGo/internal/config"
	"github.com/egoist/mygo/transfer"
)

// captureFormats negotiates without materializing providers. In particular,
// concealed copies and unsupported copies never cause a payload read.
func captureFormats(cfg config.Config, offered []transfer.Format) ([]transfer.Format, bool) {
	ignored := map[string]bool{}
	for _, name := range append([]string{"org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"}, cfg.IgnoredPasteboardTypes...) {
		ignored[strings.ToLower(canonicalFormat(name))] = true
	}
	enabled, plain := false, false
	for _, format := range offered {
		name := canonicalFormat(string(format))
		if ignored[strings.ToLower(name)] {
			return nil, false
		}
		switch category(name) {
		case "text":
			enabled = enabled || cfg.SaveText
		case "image":
			enabled = enabled || cfg.SaveImages
		case "file":
			enabled = enabled || cfg.SaveFiles
		}
		plain = plain || name == "text/plain"
	}
	if !enabled {
		return nil, false
	}
	var formats []transfer.Format
	for _, format := range offered {
		name := canonicalFormat(string(format))
		if isUnpersistable(name) {
			continue
		}
		switch category(name) {
		case "text":
			// Swift tests empty/ignored strings (and their rich fallback)
			// before subtracting disabled types from each pasteboard item.
			if !cfg.SaveText && !plain {
				continue
			}
		case "image":
			if !cfg.SaveImages {
				continue
			}
		case "file":
			// URIList can also be an ordinary web URL auxiliary flavor.
			if !cfg.SaveFiles && !(name == uriListFormat && cfg.SaveText) {
				continue
			}
		}
		formats = append(formats, format)
	}
	return formats, len(formats) > 0
}

func captureData(data transfer.Data, formats []transfer.Format) transfer.Data {
	keep := make(map[transfer.Format]bool, len(formats))
	for _, format := range formats {
		keep[format] = true
	}
	var items []transfer.Item
	for _, item := range data.Items() {
		var reps []transfer.Representation
		for _, format := range item.Formats() {
			if keep[format] {
				reps = append(reps, transfer.Lazy(format, func() ([]byte, error) { return item.Read(format) }))
			}
		}
		if len(reps) > 0 {
			items = append(items, transfer.NewItem(reps...))
		}
	}
	return transfer.New(items...)
}

// readForCapture is also used by the provider regression tests: the reader is
// given only representations the capture pipeline is allowed to request.
func readForCapture(cfg config.Config, offered []transfer.Format, read func(...transfer.Format) (transfer.Data, error)) (transfer.Data, bool, error) {
	formats, ok := captureFormats(cfg, offered)
	if !ok {
		return transfer.Data{}, false, nil
	}
	data, err := read(formats...)
	return data, true, err
}
