func clipboardStore(t *testing.T) *model.Store {
	t.Helper()
	store, err := model.Open(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	return store
}

func buildCopy(t *testing.T, store *model.Store, cfg config.Config, items ...transfer.Item) *model.Item {
	t.Helper()
	it, ok, err := Build(store, cfg, transfer.New(items...))
	if err != nil || !ok {
		t.Fatalf("copy rejected: ok=%v err=%v", ok, err)
	}
	return it
}

func TestIgnoredTypeRejectsWholeClipboardCopy(t *testing.T) {
	for _, marker := range []string{"org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType", "org.maccy.ConfidentialType"} {
		t.Run(marker, func(t *testing.T) {
			store := clipboardStore(t)
			cfg := *config.Default()
			cfg.IgnoredPasteboardTypes = []string{"org.maccy.ConfidentialType"}
			_, ok, err := Build(store, cfg, transfer.New(
				transfer.NewItem(transfer.Bytes(transfer.Text, []byte("sensitive text"))),
				transfer.NewItem(transfer.Bytes(transfer.Format(marker), nil)),
			))
			if err != nil || ok {
				t.Fatalf("ignored marker did not reject the entire copy: ok=%v err=%v", ok, err)
			}
			files, _ := os.ReadDir(filepath.Join(store.Dir(), "blobs"))
			if len(files) != 0 {
				t.Fatal("ignored copy left plaintext on disk")
			}
		})
	}
}

