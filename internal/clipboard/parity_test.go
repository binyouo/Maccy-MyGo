func TestRestoreMergedFormatsAndSourceMarkers(t *testing.T) {
	store := clipboardStore(t)
	it := buildCopy(t, store, *config.Default(),
		transfer.NewItem(transfer.Bytes(transfer.Text, []byte("first"))),
		transfer.NewItem(transfer.Bytes(transfer.Text, []byte("last"))),
	)
	it.Application = "com.example.Source"
	data, err := Data(store, it, false)
	if err != nil {
		t.Fatal(err)
	}
	b, _ := data.Read(transfer.Text)
	if string(b) != "last" {
		t.Fatalf("repeated format was not replaced: %q", b)
	}
	if _, err := data.Read(transfer.Format(FromMaccyType)); err != nil {
		t.Fatal("missing from-Maccy marker")
	}
	b, err = data.Read(transfer.Format(SourceType))
	if err != nil || string(b) != it.Application {
		t.Fatalf("source marker = %q, %v", b, err)
	}
	copy := buildCopy(t, store, *config.Default(), data.Items()...)
	found := false
	for _, c := range copy.Contents {
		found = found || c.Type == FromMaccyType
	}
	if !found {
		t.Fatal("capture discarded or lowercased the from-Maccy marker")
	}
}

