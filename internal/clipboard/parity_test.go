func TestWatcherCanRestartAfterStop(t *testing.T) {
	cfg, err := config.Load(filepath.Join(t.TempDir(), "config.json"))
	if err != nil {
		t.Fatal(err)
	}
	w := New(cfg, clipboardStore(t))
	w.Start()
	first := w.stopCh
	w.Stop()
	w.Start()
	defer w.Stop()
	if w.stopCh == first {
		t.Fatal("restarted watcher reused a closed stop channel")
	}
	select {
	case <-w.stopCh:
		t.Fatal("restarted watcher is already stopped")
	default:
	}
}

