func TestUnpersistableTypesAreNotReadOrStored(t *testing.T) {
	for _, format := range []string{"dyn.example", "com.microsoft.ole.source.123", "com.apple.webarchive", "Apple Web Archive pasteboard type", "application/x-webarchive"} {
		read := false
		it := buildCopy(t, clipboardStore(t), *config.Default(), transfer.NewItem(
			transfer.Bytes(transfer.Text, []byte("keep this")),
			transfer.Lazy(transfer.Format(format), func() ([]byte, error) { read = true; return []byte("large archive"), nil }),
		))
		if read || len(it.Contents) != 1 || it.Contents[0].Type != "text/plain" {
			t.Fatalf("unpersistable %q was read or saved: read=%v contents=%v", format, read, it.Contents)
		}
	}
}

