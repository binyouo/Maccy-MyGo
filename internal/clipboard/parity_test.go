func TestImageTakesPriorityForOCRAndUnsafeTitleScalarsAreRemoved(t *testing.T) {
	store := clipboardStore(t)
	it := buildCopy(t, store, *config.Default(), transfer.NewItem(
		transfer.Bytes(transfer.Text, []byte("image text")), transfer.Bytes(transfer.PNG, []byte("image bytes")),
	))
	if it.Title != "Image" || !HasImage(it) {
		t.Fatal("image with a string flavor lost its OCR placeholder")
	}
	it = buildCopy(t, store, *config.Default(), transfer.NewItem(transfer.Bytes(transfer.Text, []byte("文字\ufffc\u0301\ufffc"))))
	if strings.ContainsRune(it.Title, '\ufffc') || !strings.ContainsRune(Text(store, it), '\ufffc') {
		t.Fatal("unsafe scalar filtering modified content or left it in the title")
	}
}

