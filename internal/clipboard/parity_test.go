func remoteFileCopy(t *testing.T, path string, reps ...transfer.Representation) transfer.Item {
	t.Helper()
	data, err := transfer.FileData(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, format := range data.Items()[0].Formats() {
		value, err := data.Items()[0].Read(format)
		if err != nil {
			t.Fatal(err)
		}
		reps = append(reps, transfer.Bytes(format, value))
	}
	reps = append(reps, transfer.Bytes(transfer.Format(remoteClipboardType), []byte("1")))
	return transfer.NewItem(reps...)
}

func jpegFixture(t *testing.T) (string, []byte) {
	t.Helper()
	bitmap := image.NewRGBA(image.Rect(0, 0, 3, 2))
	bitmap.Set(1, 1, color.RGBA{R: 20, G: 90, B: 180, A: 255})
	var encoded bytes.Buffer
	if err := jpeg.Encode(&encoded, bitmap, nil); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "remote image.jpeg")
	if err := os.WriteFile(path, encoded.Bytes(), 0o600); err != nil {
		t.Fatal(err)
	}
	return path, encoded.Bytes()
}

func TestUniversalClipboardAuxiliaryFileDoesNotOverrideText(t *testing.T) {
	for _, value := range []struct {
		format    transfer.Format
		raw, want string
	}{
		{transfer.Text, "remote plain text", "remote plain text"},
		{"text/rtf", `{\rtf1\ansi remote rich text}`, "remote rich text"},
		{transfer.HTML, `<b>remote HTML</b>`, "remote HTML"},
	} {
		store := clipboardStore(t)
		path, _ := jpegFixture(t)
		it := buildCopy(t, store, *config.Default(), remoteFileCopy(t, path, transfer.Bytes(value.format, []byte(value.raw))))
		if Text(store, it) != value.want || it.Title != value.want || HasImage(it) {
			t.Fatalf("auxiliary remote file overrode %s: title=%q text=%q image=%v", value.format, it.Title, Text(store, it), HasImage(it))
		}
		if len(it.Files) != 1 || it.Files[0] != path {
			t.Fatal("display filtering discarded the original file representation")
		}
		restored, err := Data(store, it, false)
		files, fileErr := restored.Files()
		if err != nil || fileErr != nil || len(files) != 1 || files[0] != path {
			t.Fatalf("original auxiliary file could not be restored: files=%v err=%v/%v", files, err, fileErr)
		}
	}
}

func TestUniversalClipboardJPEGReadsFileWithoutChangingRestoreFormats(t *testing.T) {
	store := clipboardStore(t)
	path, encoded := jpegFixture(t)
	cfg := *config.Default()
	cfg.SaveImages = false // Swift still accepts the enabled file-URL flavor.
	it := buildCopy(t, store, cfg, remoteFileCopy(t, path))
	if !HasImage(it) || it.Title != "Image" {
		t.Fatal("remote JPEG file was not treated as an OCR/preview image")
	}
	data, err := ImageData(store, it)
	if err != nil || !bytes.Equal(data, encoded) {
		t.Fatalf("remote JPEG bytes not available for preview: %v", err)
	}
	restored, err := Data(store, it, false)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := restored.Read(transfer.Format("image/jpeg")); err == nil {
		t.Fatal("preview file decoding invented a clipboard image representation")
	}
	files, err := restored.Files()
	if err != nil || len(files) != 1 || files[0] != path {
		t.Fatal("remote JPEG's original file URL was lost")
	}
	cfg.SaveFiles, cfg.SaveImages = false, true
	if _, ok, _ := Build(store, cfg, transfer.New(remoteFileCopy(t, path))); ok {
		t.Fatal("remote JPEG file URL bypassed disabled file storage")
	}
}

func TestUniversalClipboardRealImageTakesPriorityOverAuxiliaryFile(t *testing.T) {
	store := clipboardStore(t)
	path, _ := jpegFixture(t)
	imageBytes := []byte("original image representation")
	it := buildCopy(t, store, *config.Default(), remoteFileCopy(t, path, transfer.Bytes(transfer.PNG, imageBytes)))
	got, err := ImageData(store, it)
	if err != nil || !bytes.Equal(got, imageBytes) {
		t.Fatal("auxiliary file replaced the actual clipboard image representation")
	}
}
