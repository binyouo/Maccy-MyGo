func TestRTFAndHTMLUseDecodedPreviewText(t *testing.T) {
	for _, tt := range []struct{ format, data, want string }{
		{"text/rtf", `{\rtf1\ansi Hello \u19990?\u30028?}`, "Hello 世界"},
		{"text/html", `<p>Hello &quot;世界&quot;</p><p>Next</p><script>hidden()</script>`, "Hello \"世界\"\nNext"},
	} {
		t.Run(tt.format, func(t *testing.T) {
			store := clipboardStore(t)
			cfg := *config.Default()
			cfg.ShowSpecialSymbols = false
			it := buildCopy(t, store, cfg, transfer.NewItem(transfer.Bytes(transfer.Format(tt.format), []byte(tt.data))))
			if got := Text(store, it); got != tt.want {
				t.Fatalf("decoded text = %q, want %q", got, tt.want)
			}
			if it.Title != tt.want {
				t.Fatalf("decoded title = %q, want %q", it.Title, tt.want)
			}
		})
	}
}

