const (
	fileListFormat = "application/x-mygo-file-list"
	uriListFormat  = "text/uri-list"
)

// fingerprint hashes every advertised representation of data.
func Fingerprint(data transfer.Data) string {
	h := sha256.New()
	items := data.Items()
	var count [8]byte
	binary.BigEndian.PutUint64(count[:], uint64(len(items)))
	h.Write(count[:])
	for _, it := range items {
		fs := it.Formats()
		names := make([]string, len(fs))
		for i, f := range fs {
			names[i] = string(f)
		}
		sort.Strings(names)
		binary.BigEndian.PutUint64(count[:], uint64(len(names)))
		h.Write(count[:])
		for _, name := range names {
			b, err := it.Read(transfer.Format(name))
			if err != nil {
				continue
			}
			var n [8]byte
			binary.BigEndian.PutUint64(n[:], uint64(len(name)))
			h.Write(n[:])
			h.Write([]byte(name))
			binary.BigEndian.PutUint64(n[:], uint64(len(b)))
			h.Write(n[:])
			h.Write(b)
		}
	}
	return hex.EncodeToString(h.Sum(nil))
}

func isUnpersistable(name string) bool {
	lower := strings.ToLower(name)
	switch {
	case strings.HasPrefix(lower, "dyn."),
		strings.HasPrefix(lower, "com.microsoft.ole.source."),
		lower == "com.apple.webarchive",
		lower == "application/x-webarchive",
		lower == "application/x-apple-webarchive",
		lower == "apple web archive pasteboard type":
		return true
	}
	return false
}

// MyGo normalizes native pasteboard types into MIME formats. Settings
// imported from Maccy still name the native types, so compare both forms.
func canonicalFormat(name string) string {
	switch strings.ToLower(name) {
	case "public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text", "public.plain-text", "nsstringpboardtype":
		return "text/plain"
	case "public.html":
		return "text/html"
	case "public.rtf", "application/rtf":
		return "text/rtf"
	case "public.png":
		return "image/png"
	case "public.tiff":
		return "image/tiff"
	case "public.jpeg":
		return "image/jpeg"
	case "public.heic":
		return "image/heic"
	case "public.file-url", "nsfilenamespboardtype", "dev.mygo.file-list":
		return fileListFormat
	}
	return name
}

func category(name string) string {
	switch {
	case name == "text/plain", name == "text/html", name == "text/rtf":
		return "text"
	case name == "image/png", name == "image/tiff", name == "image/jpeg", name == "image/heic":
		return "image"
	case name == fileListFormat, name == uriListFormat:
		return "file"
	}
	return ""
}

// Build turns freshly read clipboard data into a history item. It returns
// false when the copy should be ignored.
func Build(store *model.Store, cfg config.Config, data transfer.Data) (*model.Item, bool, error) {
	write := store.BeginBlobWrite()
	keepBlobs := false
	defer func() {
		if !keepBlobs {
			write.Release()
		}
	}()
	ignored := map[string]bool{}
	for _, t := range []string{"org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"} {
		ignored[strings.ToLower(canonicalFormat(t))] = true
	}
	for _, t := range cfg.IgnoredPasteboardTypes {
		ignored[strings.ToLower(canonicalFormat(t))] = true
	}
	// Clipboard.shouldIgnore(types) rejects the whole copy when any
	// concealed/ignored marker is advertised, rather than saving its text.
	enabled := false
	for _, f := range data.Formats() {
		name := canonicalFormat(string(f))
		if ignored[strings.ToLower(name)] {
			return nil, false, nil
		}
		switch category(name) {
		case "text":
			enabled = enabled || cfg.SaveText
		case "image":
			enabled = enabled || cfg.SaveImages
		case "file":
			if name == uriListFormat {
				files, _ := data.Files()
				enabled = enabled || cfg.SaveFiles && len(files) > 0
			} else {
				enabled = enabled || cfg.SaveFiles
			}
		}
	}
	if !enabled {
		return nil, false, nil
	}

	var contents []model.Content
	var text string
	var hasText bool
	var files []string

	for _, it := range data.Items() {
		plain, hasPlain := itemText(it, "text/plain")
		if hasPlain && strings.TrimSpace(plain) == "" && itemRichText(it) == "" {
			continue
		}
		if shouldIgnoreText(cfg.IgnoreRegexp, plain, hasPlain) {
			continue
		}
		itemFiles, _ := transfer.New(it).Files()
		if cfg.SaveFiles {
			files = append(files, itemFiles...)
		}
		wordLink := hasFormat(it, "com.microsoft.Link-Source") && hasFormat(it, "com.microsoft.ObjectLink")
		for _, f := range it.Formats() {
			name := canonicalFormat(string(f))
			if isUnpersistable(name) {
				continue
			}
			cat := category(name)
			if name == uriListFormat && len(itemFiles) == 0 {
				// MyGo uses URIList for both public.url and file URLs.
				// A web URL is an auxiliary representation, not a file.
				cat = ""
			}
			switch cat {
			case "text":
				if !cfg.SaveText {
					continue
				}
			case "image":
				if !cfg.SaveImages {
					continue
				}
			case "file":
				if !cfg.SaveFiles {
					continue
				}
			default:
				// Unknown format: keep it only if any content saving is on.
				if !cfg.SaveText && !cfg.SaveImages && !cfg.SaveFiles {
					continue
				}
			}
			if cat == "file" {
				continue // reconstructed from this item's accepted file URLs
			}
			// Word bookmark links carry a misleading PDF representation.
			if wordLink && (strings.EqualFold(name, "com.microsoft.Link-Source") || strings.EqualFold(name, "com.microsoft.ObjectLink") || name == "application/pdf") {
				continue
			}
			b, err := it.Read(f)
			if err != nil {
				continue
			}
			if name == "text/plain" && !hasText {
				text = string(b)
				hasText = true
			}
			h, size, err := write.PutBlob(b)
			if err != nil {
				return nil, false, err
			}
			contents = append(contents, model.Content{Type: name, Hash: h, Size: size})
		}
	}

	if len(contents) == 0 && len(files) == 0 {
		return nil, false, nil
	}

	it := &model.Item{
		Files:        files,
		Contents:     contents,
		PendingBlobs: write,
	}
	files = previewFiles(it)
	hasImage := HasImage(it)
	rich := hasRichText(contents)
	var body string
	if !hasImage && len(files) == 0 && text == "" && rich {
		body = richTextContents(store, contents)
	}
	title := generateTitle(cfg, text, files, hasImage, rich, body)
	it.Title = title
	keepBlobs = true
	return it, true, nil
}

func hasFormat(item transfer.Item, format string) bool {
	for _, f := range item.Formats() {
		if strings.EqualFold(canonicalFormat(string(f)), canonicalFormat(format)) {
			return true
		}
	}
	return false
}

func itemText(item transfer.Item, format string) (string, bool) {
	for _, f := range item.Formats() {
		if canonicalFormat(string(f)) == format {
			b, err := item.Read(f)
			return string(b), err == nil
		}
	}
	return "", false
}

func itemRichText(item transfer.Item) string {
	if s, ok := itemText(item, "text/rtf"); ok {
		if text := parseRichText("text/rtf", []byte(s)); text != "" {
			return text
		}
	}
	if s, ok := itemText(item, "text/html"); ok {
		return parseRichText("text/html", []byte(s))
	}
	return ""
}

func shouldIgnoreText(patterns []string, text string, hasPlain bool) bool {
	if !hasPlain {
		return false
	}
	for _, pattern := range patterns {
		rx, err := regexp2.Compile(pattern, 0)
		if err != nil {
			return false // matches Swift's invalid-pattern short circuit
		}
		rx.MatchTimeout = 100 * time.Millisecond
		matched, err := rx.MatchString(text)
		if err == nil && matched {
			return true
		}
	}
	return false
}

func hasRichText(contents []model.Content) bool {
	for _, c := range contents {
		if c.Type == "text/html" || c.Type == "text/rtf" {
			return true
		}
	}
	return false
}
func richTextContents(store *model.Store, contents []model.Content) string {
	for _, format := range []string{"text/rtf", "text/html"} {
		for _, c := range contents {
			if c.Type != format {
				continue
			}
			b, err := store.ReadBlob(c.Hash)
			if err != nil {
				break
			}
			text := parseRichText(format, b)
			if text != "" {
				return text
			}
			break
		}
	}
	return ""
}

func parseRichText(format string, data []byte) string {
	if format == "text/rtf" {
		if !strings.HasPrefix(strings.TrimSpace(string(data)), "{\\rtf") {
			return ""
		}
		return richtext.ParseRTF(data).PlainText()
	}
	return richtext.ParseHTML(string(data)).PlainText()
}

// Text follows HistoryItem.previewableText: files first, then the full
// plain-text representation, RTF, HTML, and finally the stored title.
// It never truncates text or substitutes display-only special symbols.
func Text(store *model.Store, item *model.Item) string {
	if item == nil {
		return ""
	}
	if files := previewFiles(item); len(files) > 0 {
		return fileTitles(files)
	}
	for _, c := range item.Contents {
		if canonicalFormat(c.Type) != "text/plain" {
			continue
		}
		if b, err := store.ReadBlob(c.Hash); err == nil && len(b) > 0 {
			return string(b)
		}
		break
	}
	if text := richTextContents(store, item.Contents); text != "" {
		return text
	}
	return item.Title
}

func fileTitles(files []string) string {
	urls := make([]string, len(files))
	for i, file := range files {
		path := filepath.ToSlash(file)
		if !strings.HasPrefix(path, "/") {
			path = "/" + path
		}
		urls[i] = "file://" + path
	}
	return strings.Join(urls, "\n")
}

func shorten(s string, n int) string {
	if n <= 0 {
		return ""
	}
	characters := uniseg.NewGraphemes(s)
	for i := 0; characters.Next(); i++ {
		if i == n {
			start, _ := characters.Positions()
			return s[:start]
		}
	}
	return s
}

func generateTitle(cfg config.Config, text string, files []string, hasImage, rich bool, htmlBody string) string {
	var title string
	switch {
	case hasImage:
		title = "Image" // placeholder until the watcher finishes OCR
	case len(files) > 0:
		title = fileTitles(files)
	case text != "":
		title = text
	case rich:
		title = htmlBody
	default:
		title = text
	}
	title = shorten(title, 1000)
	title = strings.ReplaceAll(title, "\ufffc", "")
	if cfg.ShowSpecialSymbols {
		// Mark leading and trailing spaces, and newlines and tabs.
		title = replaceEdgeSpaces(title)
		title = strings.ReplaceAll(title, "\n", "⏎")
		title = strings.ReplaceAll(title, "\t", "⇥")
	} else {
		title = strings.TrimSpace(title)
	}
	return title
}

func replaceEdgeSpaces(s string) string {
	// Replace runs of spaces at the start and end with middle dots.
	b := []rune(s)
	start := 0
	for start < len(b) && b[start] == ' ' {
		b[start] = '·'
		start++
	}
	end := len(b) - 1
	for end >= start && b[end] == ' ' {
		b[end] = '·'
		end--
	}
	return string(b)
}

// Describe is a short human description for debugging.
func Describe(it *model.Item) string {
	return fmt.Sprintf("%s (%d contents)", it.Title, len(it.Contents))
}
